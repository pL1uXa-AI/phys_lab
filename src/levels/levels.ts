/**
 * Уровни кампании: описание, условия проверки, теория.
 *
 * Идея взята из logic_lab: уровень — это данные, а не код. Условие проверки
 * описывается декларативно (`LevelCheck`), а вычисляет его отдельный модуль
 * `checks.ts`, знающий про физику.
 *
 * Почему условия такие. «Посмотри, что кристалл плавится» проверить нельзя,
 * а вот «доля подвижных частиц превысила 25 %» и «энергия перестала падать» —
 * можно, и это ровно те величины, по которым физик и сам судит о фазе.
 * Каждое условие снабжено подсказкой: если игрок не проходит проверку,
 * он видит, ЧТО именно не выполнено, а не «неправильно».
 */

import type { LatticeKind, ThermostatKind, BoundaryMode, WorldParams } from '../core/types.js';

/**
 * Условие проверки одного признака.
 *
 * Значение величины берётся после `equilibrate` шагов и усредняется по
 * `sampleWindow` шагам: одиночный замер слишком шумный, чтобы по нему
 * принимать решение.
 */
export type LevelCheck =
  /** Доля частиц, сместившихся больше чем на половину σ. */
  | { kind: 'mobility'; min?: number; max?: number; label: string }
  /** Средний квадрат смещения за окно — мера диффузии. */
  | { kind: 'msd'; min?: number; max?: number; label: string }
  /** Температура (для уровней без термостата — установившаяся). */
  | { kind: 'temperature'; min?: number; max?: number; label: string }
  /** Высота первого пика g(r): кристалл — высокий, жидкость — низкий. */
  | { kind: 'orderPeak'; min?: number; max?: number; label: string }
  /** Доля частиц внутри сферы заданного радиуса — «собрались вместе». */
  | { kind: 'confinement'; radius: number; min?: number; max?: number; label: string }
  /** Число частиц, оставшихся в ящике (для испарения). */
  | { kind: 'remaining'; min?: number; max?: number; label: string }
  /** Число «улетевших» частиц. */
  | { kind: 'escaped'; min?: number; max?: number; label: string }
  /** Средняя скорость — грубая проверка «нагрелся / остыл». */
  | { kind: 'meanSpeed'; min?: number; max?: number; label: string }
  /** Относительное изменение потенциальной энергии на частицу от старта. */
  | { kind: 'energyDrop'; min?: number; max?: number; label: string }
  /** Давление. */
  | { kind: 'pressure'; min?: number; max?: number; label: string }
  /** Плотность: обычно требуется довести её до заданной. */
  | { kind: 'density'; min?: number; max?: number; label: string }
  /** Относительный дрейф полной энергии — проверка симплектичности. */
  | { kind: 'energyDrift'; max: number; label: string }
  /** Тип термостата. */
  | { kind: 'thermostat'; value?: ThermostatKind; label: string }
  /** Тип граничных условий. */
  | { kind: 'boundary'; value?: BoundaryMode; label: string };

/** Начальные условия уровня. */
export interface LevelSetup extends Partial<WorldParams> {
  lattice: LatticeKind;
  thermostat: ThermostatKind;
  boundary: BoundaryMode;
}

/** Уровень кампании. */
export interface Level {
  /** Идентификатор вида «level-01». */
  id: string;
  /** Название. */
  title: string;
  /** Что нужно сделать (одна строка). */
  goal: string;
  /** Краткая теория: 2–4 абзаца markdown. */
  theory: string;
  /** Формула или ключевое соотношение (markdown-блок). */
  formula?: string;
  /** Подсказки, если не получается. */
  hints: string[];
  /** Начальные параметры мира. */
  setup: LevelSetup;
  /** Сколько шагов прогнать до начала проверки (выход на режим). */
  equilibrate: number;
  /** По скольким последним шагам усреднять измерения. */
  sampleWindow: number;
  /** Условия, которые обязаны выполниться все. */
  checks: LevelCheck[];
  /** Подсказка, что делать дальше (показывается поверх сцены). */
  task: string;
}

/** Порядковый номер уровня из идентификатора. */
export function levelNumber(level: Level): number {
  const match = /(\d+)/.exec(level.id);
  return match ? Number(match[1]) : 0;
}

