/**
 * Структурный фактор S(k) — «рентгенограмма» системы в обратном пространстве.
 *
 * ─── Зачем это, если уже есть g(r) ────────────────────────────────────────
 *
 * g(r) и S(k) — пара взаимных преобразований Фурье, но видно на них разное.
 * У кристалла g(r) даёт набор пиков, у жидкости — несколько размытых, и
 * различить их «на глаз» при малой статистике трудно: пики g(r) у плотной
 * жидкости высокие, а у кристалла размываются тепловым движением.
 *
 * S(k) различает фазы резче. Причина физическая: S(k) — это отклик системы
 * на внешнюю пространственную моду с волновым числом k, то есть прямо то, что
 * измеряет дифракция. Кристалл когерентно рассеивает только на векторах
 * обратной решётки: пики бесконечно узкие по построению (их ширина задана
 * только тепловым размытием и конечным размером ящика). У жидкости ближний
 * порядок даёт широкий горб, у газа S(k) ≈ 1 на больших k — рассеяние
 * некогерентно, каждая частица «сама по себе».
 *
 * ─── Определение ──────────────────────────────────────────────────────────
 *
 *   S(k) = (1/N) · |Σ_j exp(i k·r_j)|²
 *
 * где сумма берётся по «живым» частицам, а N — их число. Это статический
 * структурный фактор (без учёта форм-фактора атома и без теплового фактора
 * Дебая — Валлера): частицы считаются точечными рассеивателями.
 *
 * ─── Почему cos/sin, а не комплексные числа ───────────────────────────────
 *
 * Сумма комплексных экспонент считается как две вещественные суммы:
 *
 *   C = Σ cos(k·r_j),  S_sin = Σ sin(k·r_j),  |Σ exp|² = C² + S_sin²
 *
 * Объект `{re, im}` на каждую частицу — это аллокация в самом горячем цикле
 * (стоимость кадра растёт как N·nk, то есть десятки миллионов операций).
 * Две вещественные суммы не аллоцируют ничего и считаются в регистрах.
 *
 * ─── Сетка векторов k: только узлы обратной решётки ящика ─────────────────
 *
 * Для периодического ящика длины L «правильные» волновые числа — это
 *
 *   k = (2π/L) · (nx, ny, nz),  nx, ny, nz — целые.
 *
 * Брать произвольный k нельзя: на нецелых векторах сумма фаз медленно
 * обходит окружность и S(k) оказывается мусором, зависящим от выбора начала
 * координат. Целые же векторы обладают двумя свойствами, на которых всё
 * держится:
 *
 *   1. Сдвиг всей системы на c не меняет S(k): Σ exp(i k·(r_j+c)) =
 *      exp(i k·c)·Σ exp(i k·r_j), а модуль множителя равен единице. Поэтому
 *      S(k) не зависит от того, где стоит начало координат.
 *   2. Заворачивание координаты через границу ящика (r → r − L) не меняет
 *      S(k), потому что k·L = 2π·nx, и фаза exp(−i·2π·nx) = 1. Это важно:
 *      интегратор заворачивает частицы в [0, L) постоянно, и без свойства 2
 *      S(k) «дёргался» бы при каждом переходе границы.
 *
 * Дополнительно сетка отбирается по модулю |k| ≤ kMax. Верхняя граница нужна
 * потому, что на больших k структура уже не видна (S → 1 у любой фазы), а
 * стоимость растёт как объём шара в обратном пространстве.
 *
 * ─── Почему сетка готовится заранее ───────────────────────────────────────
 *
 * Перебор троек (nx, ny, nz) с отбором по модулю — это сотни тысяч операций,
 * и делать их на каждый кадр (а кадры статистики идут десятками) бессмысленно:
 * при неизменном ящике список векторов и их принадлежность бинам не меняются.
 * `prepare(box)` строит их один раз; `accumulate` только суммирует фазы.
 *
 * Векторы хранятся отсортированными по бинам (порядок задаётся `binStart`):
 * так внутренний цикл идёт по непрерывной памяти, а не прыгает по ней.
 *
 * ─── Почему нет проверки «сетка вмещает радиус» ───────────────────────────
 *
 * Проверка из g(r) и списков Верле (`grid.size ≥ radius`) здесь не нужна и
 * была бы вредна: S(k) вообще не использует сетку ячеек и не ищет соседей.
 * Это ПРЯМОЕ суммирование по всем частицам для каждого вектора k, стоимость
 * O(N·nk). Радиус обрезания в определение S(k) не входит: структурный фактор —
 * свойство всей конфигурации, а не пар внутри сферы.
 */

import type { ParticleState } from './types.js';

/** Готовая кривая S(k): узлы по волновому числу и значения. */
export interface StructureCurve {
  /** Волновые числа (центры непустых бинов), по возрастанию. */
  k: Float64Array;
  /** S(k), усреднённая по кадрам и по векторам k внутри бина. */
  s: Float64Array;
}

/** Положение и высота первого пика S(k). */
export interface StructurePeak {
  k: number;
  height: number;
}

/**
 * Бюджет операций «частица × вектор» на один кадр статистики.
 *
 * ─── Откуда это число ────────────────────────────────────────────────────
 *
 * Число узлов обратной решётки внутри шара радиуса kMax растёт как L³ ~ N,
 * поэтому полная сумма S(k) стоит O(N²): замерено 590 млн пар уже при 2048
 * частицах и 56 МЛРД при 20 000. Приложение в этом режиме перестаёт
 * отвечать — это поймано по таймауту витринного скрипта, а не «на глаз».
 *
 * 2 миллиона пар — примерно 10–20 мс на кадр статистики, что сравнимо с
 * ценой g(r) на 20 000 частиц (замерено 37 мс вместе с S(k)). Кадров
 * статистики немного, и они размазаны по времени, поэтому такой бюджет
 * незаметен, тогда как квадратичный рост — фатален.
 */
const MAX_STRUCTURE_OPS = 2_000_000;
export class StructureFactor {
  /** Максимальное волновое число отбора. */
  readonly kMax: number;
  /** Число бинов по k. */
  readonly steps: number;
  /** Ширина бина по k. */
  readonly dk: number;
  /** Число отобранных векторов k (для диагностики и тестов). */
  vectorCount = 0;

  /** Компоненты векторов k, отсортированные по бинам. */
  private kx = new Float64Array(0);
  private ky = new Float64Array(0);
  private kz = new Float64Array(0);
  /**
   * Границы бинов в массивах векторов: бин b занимает
   * [binStart[b], binStart[b+1]). Бины без векторов имеют пустой диапазон.
   */
  private binStart = new Int32Array(1);

  /** Сумма S(k) по кадрам, УЖЕ усреднённая по векторам бина (см. `accumulate`). */
  private sums: Float64Array;
  private frames = 0;
  /** Длина ящика, для которой построена сетка векторов (0 — ещё не построена). */
  private preparedBox = 0;
  /**
   * Число частиц, для которого строилась сетка векторов.
   *
   * Нужно только для выбора шага прореживания: бюджет операций считается как
   * «число векторов × число частиц», и без второго множителя решение о
   * прореживании было бы неполным.
   */
  private preparedCount = 0;

  constructor(kMax = 18, steps = 90) {
    this.kMax = kMax;
    this.steps = Math.max(1, Math.round(steps));
    this.dk = kMax / this.steps;
    this.sums = new Float64Array(this.steps);
  }

  /** Число накопленных кадров. */
  get sampleCount(): number {
    return this.frames;
  }

  /** Длина ящика, под которую сейчас построена сетка векторов. */
  get preparedBoxLength(): number {
    return this.preparedBox;
  }

  /**
   * Построение сетки векторов k под ящик `box` и число частиц `count`.
   *
   * Перебор идёт не по всему кубу целых чисел, а по шару радиуса kMax:
   * для каждой пары (nx, ny) граница по nz выводится аналитически из
   * |k|² = (2π/L)²(nx² + ny² + nz²) ≤ kMax². Куб со стороной 2·ceil(kMax·L/2π)
   * на больших ящиках в разы дороже, а лишние тройки всё равно отбрасываются.
   *
   * @param count число частиц — нужно, чтобы решить, требуется ли прореживание
   */
  prepare(box: number, count = this.preparedCount): void {
    if (!(box > 0) || !Number.isFinite(box)) return;
    this.preparedCount = Math.max(0, Math.floor(count));

    const twoPiOverL = (2 * Math.PI) / box;
    const kMaxSq = this.kMax * this.kMax;
    const nMax = Math.max(1, Math.ceil(this.kMax / twoPiOverL));
    const invDk = 1 / this.dk;

    // Динамические массивы: число векторов заранее неизвестно, зависит от L.
    const ax: number[] = [];
    const ay: number[] = [];
    const az: number[] = [];
    const binOf: number[] = [];
    const counts = new Int32Array(this.steps);

    for (let nx = -nMax; nx <= nMax; nx++) {
      const kx = twoPiOverL * nx;
      const remX = kMaxSq - kx * kx;
      if (remX < 0) continue;
      for (let ny = -nMax; ny <= nMax; ny++) {
        const ky = twoPiOverL * ny;
        const remXY = remX - ky * ky;
        if (remXY < 0) continue;
        const nzLim = Math.floor(Math.sqrt(remXY) / twoPiOverL);
        for (let nz = -nzLim; nz <= nzLim; nz++) {
          // Нулевой вектор пропускается: S(0) для конечной системы — это не
          // физическая сжимаемость, а просто N («весь ящик целиком»), и на
          // фоне остальных бинов это гигантский выброс. Первый пик ищется
          // при k > 0.5, так что нулевой вектор не нужен нигде.
          if (nx === 0 && ny === 0 && nz === 0) continue;
          const kz = twoPiOverL * nz;
          const km = Math.sqrt(kx * kx + ky * ky + kz * kz);
          let b = Math.floor(km * invDk);
          // Ровно на границе kMax (|k| == kMax) бина может не хватить —
          // зажимаем в последний, а не теряем вектор.
          if (b < 0) b = 0;
          else if (b >= this.steps) b = this.steps - 1;
          ax.push(kx);
          ay.push(ky);
          az.push(kz);
          binOf.push(b);
          counts[b]++;
        }
      }
    }

    // Число векторов-кандидатов ДО прореживания.
    let candidates = 0;
    for (let b = 0; b < this.steps; b++) candidates += counts[b];

    /*
     * Прореживание внутри оболочек — только когда иначе считать нельзя.
     *
     * ─── Почему оно вообще нужно ─────────────────────────────────────────────
     *
     * Число узлов обратной решётки внутри шара радиуса kMax растёт как
     * L³ ~ N. Стоимость кадра статистики выходит O(N²): замерено 590 млн пар
     * «частица-вектор» уже при 2048 частицах и 56 МЛРД при 20 000 — это не
     * «медленно», а «приложение перестаёт отвечать» (поймано по таймауту
     * витринного скрипта).
     *
     * ─── Почему это не портит физику ─────────────────────────────────────────
     *
     * S(k) усредняется ПО ОБОЛОЧКЕ, а внутри оболочки все векторы
     * равноправны: система изотропна, и каждый даёт статистически одно и то
     * же. Взять каждый m-й — значит оценить то же среднее по подвыборке:
     * оценка несмещённая, растёт лишь дисперсия, а её сглаживают кадры.
     *
     * ─── Почему отбор детерминированный ──────────────────────────────────────
     *
     * Берётся именно каждый m-й вектор, а не случайный: одна и та же
     * конфигурация обязана давать одну и ту же кривую, иначе «сохранил —
     * загрузил» и сравнение запусков перестали бы сходиться.
     *
     * Пока пар «частица × вектор» меньше бюджета, шаг равен единице и
     * результат ТОЧНЫЙ: сумма идёт по всем векторам, как в эталонном тесте.
     */
    const perFrame = candidates * Math.max(1, this.preparedCount);
    const shellStride = perFrame <= MAX_STRUCTURE_OPS ? 1 : Math.ceil(perFrame / MAX_STRUCTURE_OPS);

    // Границы бинов считаются ПОСЛЕ отбора: старые относились к полному
    // набору, и чтение по ним вышло бы за пределы массива.
    const binStart = new Int32Array(this.steps + 1);
    let kept = 0;
    for (let b = 0; b < this.steps; b++) {
      binStart[b] = kept;
      const take = counts[b] === 0 ? 0 : Math.ceil(counts[b] / shellStride);
      kept += take;
    }
    binStart[this.steps] = kept;

    const kx = new Float64Array(kept);
    const ky = new Float64Array(kept);
    const kz = new Float64Array(kept);
    // Сколько векторов бина уже просмотрено — по этому счётчику решается,
    // брать вектор или пропустить.
    const seen = new Int32Array(this.steps);
    const placed = new Int32Array(this.steps);
    for (let v = 0; v < ax.length; v++) {
      const b = binOf[v];
      if (seen[b]++ % shellStride !== 0) continue;
      const pos = binStart[b] + placed[b];
      placed[b]++;
      kx[pos] = ax[v];
      ky[pos] = ay[v];
      kz[pos] = az[v];
    }

    this.kx = kx;
    this.ky = ky;
    this.kz = kz;
    this.binStart = binStart;
    this.vectorCount = kept;
    this.preparedBox = box;
  }

  /**
   * Накопить S(k) за один кадр.
   *
   * Сетка векторов строится здесь же, если ящик изменился: молча считать по
   * векторам старого ящика нельзя — узлы обратной решётки сдвинутся, и кривая
   * станет суммой двух разных систем (ошибка не падает, а тихо портит физику).
   *
   * Мёртвые частицы (`alive[i] === 0`) пропускаются, а N берётся как число
   * ЖИВЫХ. У открытого ящика частицы вылетают навсегда, и если делить на
   * исходное N, S(k) систематически занижается по мере испарения.
   */
  accumulate(state: ParticleState, box: number): void {
    const count = state.count;
    const alive = state.alive;
    let n = 0;
    for (let i = 0; i < count; i++) if (alive[i] !== 0) n++;
    if (n < 1) return;

    // Сетку строим ПОСЛЕ подсчёта живых частиц: шаг прореживания зависит от
    // произведения «число векторов × число частиц», и без второго множителя
    // решение о прореживании было бы неполным.
    if (this.preparedBox !== box || this.vectorCount === 0 || this.preparedCount !== count) {
      this.prepare(box, count);
    }
    if (this.vectorCount === 0) return;

    const invN = 1 / n;
    const x = state.x;
    const y = state.y;
    const z = state.z;
    const kx = this.kx;
    const ky = this.ky;
    const kz = this.kz;
    const binStart = this.binStart;
    const sums = this.sums;

    for (let b = 0; b < this.steps; b++) {
      const start = binStart[b];
      const end = binStart[b + 1];
      if (start === end) continue;

      let acc = 0;
      for (let v = start; v < end; v++) {
        const vx = kx[v];
        const vy = ky[v];
        const vz = kz[v];
        let cosSum = 0;
        let sinSum = 0;
        for (let i = 0; i < count; i++) {
          if (alive[i] === 0) continue;
          const phase = vx * x[i] + vy * y[i] + vz * z[i];
          cosSum += Math.cos(phase);
          sinSum += Math.sin(phase);
        }
        acc += cosSum * cosSum + sinSum * sinSum;
      }

      // Делим на число векторов в бине СРАЗУ, а не в `result`: тогда `sums`
      // хранит уже усреднённую по бину величину, и усреднение по кадрам
      // остаётся честным даже если в разных кадрах было разное число живых
      // частиц (у каждой кривой — свой нормировочный множитель).
      sums[b] += acc * invN * (1 / (end - start));
    }
    this.frames++;
  }

  /**
   * Готовая кривая S(k), усреднённая по кадрам.
   *
   * Возвращаются только НЕПУСТЫЕ бины: бин без векторов k дал бы деление на
   * ноль, а держать в кривой NaN нельзя — он мгновенно «размазывается» по
   * любой обработке (поиск максимума, сглаживание, отрисовка).
   *
   * Пока не накоплено ни одного кадра, возвращаются нули, а не «нет данных»:
   * график обязан нарисовать нулевую линию, а не упасть.
   */
  result(): StructureCurve {
    const frames = Math.max(1, this.frames);
    const binStart = this.binStart;
    let used = 0;
    for (let b = 0; b < this.steps; b++) if (binStart[b + 1] > binStart[b]) used++;

    const k = new Float64Array(used);
    const s = new Float64Array(used);
    let w = 0;
    for (let b = 0; b < this.steps; b++) {
      if (binStart[b + 1] <= binStart[b]) continue;
      // Центр бина, а не его левый край: вектор с |k| внутри бина ближе к
      // центру, и систематический сдвиг кривой влево был бы заметен именно
      // на резких пиках кристалла.
      k[w] = (b + 0.5) * this.dk;
      s[w] = this.sums[b] / frames;
      w++;
    }
    return { k, s };
  }

  /**
   * Первый (самый высокий) пик при k > 0.5.
   *
   * Порог 0.5 отсекает область малых k, где S(k) определяется не структурой,
   * а конечным размером системы: вблизи k → 0 величина управляется флуктуацией
   * полного числа частиц в ящике и на одном кадре способна дать выброс,
   * сравнимый с настоящим пиком. Физический интерес — в первом максимуме
   * кривой: у кристалла это резкий пик на векторе обратной решётки, у жидкости
   * широкий горб около 2π/r_сосед.
   *
   * Возвращается МАКСИМУМ, а не первый по k: у кристалла пик (111) может
   * оказаться ниже, чем следующий (200), если тот попал в бин с меньшей
   * кратностью вырождения.
   */
  firstPeak(): StructurePeak {
    const { k, s } = this.result();
    let peakK = 0;
    let peakS = 0;
    for (let i = 0; i < k.length; i++) {
      if (k[i] <= 0.5) continue;
      if (s[i] > peakS) {
        peakS = s[i];
        peakK = k[i];
      }
    }
    return { k: peakK, height: peakS };
  }

  /**
   * Очистить накопленное.
   *
   * Сетка векторов НЕ сбрасывается: она зависит только от ящика, а не от
   * координат, и пересобирать её при каждой очистке статистики (а очистка
   * бывает частой — смена пресета, кнопка «сброс») незачем.
   */
  reset(): void {
    this.sums.fill(0);
    this.frames = 0;
  }
}
