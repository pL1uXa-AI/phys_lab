/**
 * Потенциал Леннарда-Джонса и его производные.
 *
 *   U(r) = 4ε [ (σ/r)¹² − (σ/r)⁶ ]
 *
 * В приведённых единицах ε = 1, σ = 1:
 *
 *   U(r) = 4 (r⁻¹² − r⁻⁶)
 *
 * Форма потенциала: бесконечное отталкивание при r → 0 (член r⁻¹²),
 * притяжение на средних расстояниях (член −r⁻⁶ с минимумом U = −1 при
 * r = 2^(1/6) ≈ 1.122 σ), ноль при r = σ и почти ноль за r ≈ 2.5 σ.
 *
 * Сила F = −dU/dr · r̂. Удобно считать не саму силу, а величину
 *
 *   F(r)/r = 24 (2 r⁻¹⁴ − r⁻⁸)
 *
 * — тогда Fx = (F/r)·dx, и деления на r в горячем цикле нет вовсе.
 *
 * ─── Обрезание (важно) ───────────────────────────────────────────────────
 *
 * Сырой обрезанный потенциал имеет разрыв силы в точке обрезания, из-за чего
 * энергия систематически «плывёт». Применяем схему shifted-force: из F/r
 * вычитается её значение на обрезании s = (F/r)(rc). Тогда
 *
 *   F_sf(r) = F(r) − s·r
 *
 * и сила обращается в ноль на обрезании. Потенциал, из которого такая сила
 * получается дифференцированием, уже не равен просто сдвинутому U:
 *
 *   U_sf(r) = U(r) − U(rc) + ½·s·(r² − rc²)
 *
 * Слагаемое ½s(r²−rc²) обязательно: без него энергия не соответствует силе,
 * и симплектический интегратор перестаёт сохранять энергию (проверяется
 * тестом «энергия в микроканоническом ансамбле не дрейфует»). Обычно оно
 * мало (|s| ~ 0.01), поэтому ошибку легко не заметить — но на длинном
 * прогоне она накапливается.
 */

/** Постоянные сдвига для заданного радиуса обрезания. */
export interface LjShift {
  /** s = F(rc)/rc — вычитается из (F/r) внутри обрезания. */
  forceOverR: number;
  /** U(rc) — сдвиг энергии. */
  energy: number;
  /** rc² — нужен, чтобы не возводить в квадрат радиус обрезания в цикле. */
  cutoffSq: number;
}

/** Вычисление постоянных сдвига. */
export function ljShift(cutoff: number): LjShift {
  const rc2 = cutoff * cutoff;
  const rc6 = rc2 * rc2 * rc2;
  const inv6 = 1 / rc6;
  const inv12 = inv6 * inv6;
  return {
    forceOverR: (24 * (2 * inv12 - inv6)) / rc2,
    energy: 4 * (inv12 - inv6),
    cutoffSq: rc2,
  };
}

/**
 * Сила, делённая на расстояние, для сдвинутого потенциала.
 * Возвращает `F(r)/r`, так что `Fx = value · dx`.
 * Положительное значение — отталкивание.
 */
export function ljForceOverR(r2: number, shift: LjShift): number {
  const inv2 = 1 / r2;
  const inv6 = inv2 * inv2 * inv2;
  const inv12 = inv6 * inv6;
  return 24 * (2 * inv12 - inv6) * inv2 - shift.forceOverR;
}

/**
 * Энергия пары с учётом сдвига, согласованная с `ljForceOverR`.
 * `r2` передаётся уже возведённым в квадрат — в горячем цикле он есть.
 */
export function ljEnergy(r2: number, shift: LjShift): number {
  const inv2 = 1 / r2;
  const inv6 = inv2 * inv2 * inv2;
  const inv12 = inv6 * inv6;
  return (
    4 * (inv12 - inv6) -
    shift.energy +
    0.5 * shift.forceOverR * (r2 - shift.cutoffSq)
  );
}

/**
 * Сила, действующая на частицу i со стороны частицы j.
 *
 * На вход подаётся вектор `d = r_j − r_i` — ОТ i К j. Сила на i направлена
 * против d, поэтому возвращается `−(F/r)·d`. Соглашение выбрано так, чтобы
 * знак нигде не приходилось додумывать: одна и та же функция годится и для
 * проверок направления, и для сборки полной силы в горячем цикле
 * (см. `computeForces`).
 *
 * Используется в тестах и одиночных расчётах; горячий цикл работает напрямую
 * с `ljForceOverR`, чтобы не выделять память под объекты.
 */
export function ljForce(
  dx: number,
  dy: number,
  dz: number,
  shift: LjShift,
): [number, number, number] {
  const r2 = dx * dx + dy * dy + dz * dz;
  const f = ljForceOverR(r2, shift);
  return [-f * dx, -f * dy, -f * dz];
}

/** Минимум потенциала: r_min = 2^(1/6) σ, U_min = −ε. */
export const LJ_MIN_RADIUS = Math.pow(2, 1 / 6);
export const LJ_MIN_ENERGY = -1;

/** Радиус, на котором потенциал равен нулю: r = σ. */
export const LJ_ZERO_RADIUS = 1;

/**
 * Второй вириальный коэффициент B₂(T) в приведённых единицах.
 *
 * B₂(T) = −2π ∫₀^∞ (e^{−U(r)/T} − 1) r² dr
 *
 * Интегрируем методом трапеций по «сырому» потенциалу (без сдвига —
 * сдвиг меняет B₂ незначительно, но интеграл от него расходится на больших
 * r, поэтому обрезаем и работаем с настоящим U). Нужен для графика
 * уравнения состояния: знак B₂ показывает, где притяжение побеждает
 * отталкивание.
 */
export function virialCoefficient(temperature: number): number {
  const rc = 4;
  const steps = 1200;
  const dr = rc / steps;
  let sum = 0;
  for (let i = 0; i < steps; i++) {
    const r = (i + 0.5) * dr;
    const inv6 = 1 / (r * r * r * r * r * r);
    const u = 4 * (inv6 * inv6 - inv6);
    const f = Math.exp(-u / temperature) - 1;
    sum += f * r * r * dr;
  }
  return -2 * Math.PI * sum;
}
